"""
Reliability harness: runs eval/eval_cases.json through the agent and writes
eval/results.md (a markdown table) plus a one-line summary.

Run with: python -m src.evaluate
"""

import json
import logging
import os
import sys

from src.agent import VibeAgent
from src.guardrails import GuardrailError


def evaluate_case(agent: VibeAgent, case: dict) -> dict:
    row = {"query": case["query"], "criteria": "", "result": "", "passed": False, "confidence": None, "top3": ""}

    if case.get("expect_error"):
        row["criteria"] = "rejected by guardrail"
        try:
            agent.run(case["query"])
            row["result"] = "Fail: accepted"
        except GuardrailError as e:
            row["passed"] = True
            row["result"] = f"Pass: {e}"
        return row

    res = agent.run(case["query"], k=5)
    top3 = [s for s, _, _ in res.recommendations[:3]]
    row["confidence"] = res.confidence
    row["top3"] = ", ".join(f"{s['title']} ({s['genre']})" for s in top3)

    if case.get("expect_warning"):
        row["criteria"] = "warns user (low confidence)"
        row["passed"] = bool(res.warnings)
        row["result"] = "Pass" if row["passed"] else "Fail: no warning"
        return row

    expect = case["expect_genres"]
    row["criteria"] = f"top 3 has {'/'.join(expect)}; conf >= {case['min_conf']}"
    genre_ok = any(s["genre"] in expect for s in top3)
    conf_ok = res.confidence >= case["min_conf"]
    row["passed"] = genre_ok and conf_ok
    if row["passed"]:
        row["result"] = "Pass"
    else:
        why = []
        if not genre_ok:
            why.append("expected genre missing")
        if not conf_ok:
            why.append("confidence too low")
        if res.warnings:
            why.append("warned: " + res.warnings[0])
        else:
            why.append("no warning shown")
        row["result"] = "Fail: " + "; ".join(why)
    return row


def main() -> int:
    logging.basicConfig(level=logging.WARNING)
    agent = VibeAgent()
    with open("eval/eval_cases.json") as f:
        cases = json.load(f)
    rows = [evaluate_case(agent, c) for c in cases]

    passed = sum(r["passed"] for r in rows)
    confs = [r["confidence"] for r in rows if r["confidence"] is not None]
    answered = [r["confidence"] for r, c in zip(rows, cases) if r["confidence"] is not None and c.get("expect_genres")]
    summary = (
        f"{passed} out of {len(rows)} cases passed. "
        f"Average confidence {sum(confs) / len(confs):.2f} across {len(confs)} answered requests "
        f"({sum(answered) / len(answered):.2f} on in-catalog requests)."
    )

    lines = ["# Evaluation Results", "", "Generated by `python -m src.evaluate`.", "", f"**Summary:** {summary}", "",
             "| # | Test Input | Evaluation Criteria | Confidence | Top 3 | Result |",
             "|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        conf = "" if r["confidence"] is None else f"{r['confidence']:.2f}"
        q = r["query"].strip() or "(empty)"
        lines.append(f"| {i} | \"{q}\" | {r['criteria']} | {conf} | {r['top3']} | {r['result']} |")
    os.makedirs("eval", exist_ok=True)
    with open("eval/results.md", "w") as f:
        f.write("\n".join(lines) + "\n")

    for r in rows:
        mark = "PASS" if r["passed"] else "FAIL"
        print(f"[{mark}] {r['query'].strip() or '(empty)'!r:45} conf={r['confidence']}  {r['result']}")
    print()
    print(summary)
    print("Table written to eval/results.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
